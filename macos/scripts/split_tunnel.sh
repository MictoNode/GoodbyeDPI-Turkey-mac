#!/usr/bin/env bash
# Split-tunnel mode: send only the domains listed in split-tunnel-domains.txt
# through ciadpi and let everything else connect directly.
#
# The service_install_* scripts set a system-wide SOCKS proxy, so every TLS
# connection goes through the desync. That also hits sites which were never
# blocked, and some of them reject the split ClientHello (sahibinden.com
# answers "sslv3 alert illegal parameter", vercel.com and others just time
# out). This script swaps the system-wide SOCKS setting for a PAC file that
# matches the domain list.
#
# Matched domains are routed "PROXY 127.0.0.1:8080": GOST turns the HTTP
# proxy into SOCKS5 for ciadpi. The Discord desktop app (Chromium) follows
# this PAC. Its updater (Squirrel) ignores system PAC entirely and only
# honors HTTP(S)_PROXY env vars; launch Discord through `macos/discord-proxy`
# to give those vars to the updater without exporting them session-wide.
#
# 'on' also (re)installs the GOST bridge as a launchd daemon when missing.
# Run it after a service_install_* script.
#
# Usage: sudo ./split_tunnel.sh on|off|status

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

SOCKS_HOST="127.0.0.1"
SOCKS_PORT="${CIADPI_PORT:-1080}"
DOMAINS_SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/split-tunnel-domains.txt"
DOMAINS="$ETC_DIR/split-tunnel-domains.txt"

[[ $EUID -eq 0 ]] || { echo "sudo ile calistirin: sudo $0 ${1:-}" >&2; exit 1; }

write_pac() {
    mkdir -p "$ETC_DIR"
    [[ -f "$DOMAINS" ]] || cp "$DOMAINS_SRC" "$DOMAINS"
    {
        echo "// Generated by split_tunnel.sh from $DOMAINS"
        echo "// Single PROXY value (GOST :$GOST_PORT): Discord's updater (CFNetwork)"
        echo "// chokes on multi-value returns like \"PROXY ...; SOCKS5 ...\"."
        echo "function FindProxyForURL(url, host) {"
        echo "  if ("
        grep -vE '^[[:space:]]*(#|$)' "$DOMAINS" | while read -r d; do
            echo "      shExpMatch(host, \"$d\") || shExpMatch(host, \"*.$d\") ||"
        done
        echo "      false"
        echo "  ) {"
        echo "    return \"PROXY $SOCKS_HOST:$GOST_PORT\";"
        echo "  }"
        echo "  return \"DIRECT\";"
        echo "}"
    } >"$PAC_FILE"
    chmod 644 "$PAC_FILE"
}

# Apply to every enabled service, not just the active one: a PAC set only on
# Wi-Fi stops applying as soon as the Mac switches to ethernet or tethering.
apply_pac_to_services() {
    while read -r svc; do
        networksetup -setsocksfirewallproxystate "$svc" off || true
        networksetup -setautoproxyurl "$svc" "$PAC_URL" || true
        networksetup -setautoproxystate "$svc" on || true
    done < <(network_services)
}

restore_socks_to_services() {
    while read -r svc; do
        networksetup -setautoproxystate "$svc" off || true
        networksetup -setsocksfirewallproxy "$svc" "$SOCKS_HOST" "$SOCKS_PORT" || true
        networksetup -setsocksfirewallproxystate "$svc" on || true
    done < <(network_services)
}

case "${1:-status}" in
on)
    log "GOST köprüsü kuruluyor ve başlatılıyor..."
    install_gost_service
    if wait_port "$GOST_PORT" 20; then
        log "GOST hazir: http://127.0.0.1:${GOST_PORT} (log: $GOST_LOG)"
    else
        warn "GOST :${GOST_PORT} dinlemiyor — log: $GOST_LOG"
    fi

    write_pac
    install_pac_server
    wait_port "$PAC_PORT" 20 || { err "PAC sunucusu ($PAC_URL) baslatilamadi."; exit 1; }

    if ! wait_port "$SOCKS_PORT" 8; then
        warn "ciadpi :${SOCKS_PORT} dinlemiyor — önce bir service_install_* scripti kurun."
    fi

    # Remove the legacy GUI-wide proxy env bridge installed by older
    # versions. It made every app launched afterwards depend on GOST and cut
    # their connectivity when GOST stopped. Discord's updater now uses the
    # scoped macos/discord-proxy launcher instead.
    remove_gost_env_agent
    clear_gost_env_now

    apply_pac_to_services

    # Split DNS too: snapshot the full-tunnel DNS (once), then replace the
    # system-wide Yandex DNS with per-domain /etc/resolver entries so only the
    # listed domains use Yandex and everything else resolves via DHCP/ISP.
    if [[ ! -f "$SPLIT_DNS_STATE" ]]; then
        save_split_dns_state
    fi
    install_split_resolvers
    clear_dns_all

    echo "Split tunnel acik. ciadpi'den gecen domainler ($DOMAINS):"
    grep -vE '^[[:space:]]*(#|$)' "$DOMAINS" | sed 's/^/  - /'
    ;;
off)
    remove_gost_env_agent
    clear_gost_env_now
    remove_gost_service
    remove_pac_server
    restore_socks_to_services
    remove_split_resolvers
    restore_split_dns_state
    echo "Split tunnel kapali; sistem geneli SOCKS ve DNS geri acildi."
    ;;
status)
    while read -r svc; do
        printf '%-22s PAC=%s SOCKS=%s\n' "$svc" \
            "$(networksetup -getautoproxyurl "$svc" 2>/dev/null | tr '\n' ' ')" \
            "$(networksetup -getsocksfirewallproxy "$svc" 2>/dev/null | awk -F': ' '/^Enabled/{print $2}')"
    done < <(network_services)
    if [[ -f "$GOST_PLIST" ]]; then
        echo "GOST köprüsü: kurulu ($GOST_PLIST)"
    fi
    if [[ -f "$GOST_ENV_PLIST" ]]; then
        echo "Eski GUI env köprüsü: kurulu ($GOST_ENV_PLIST)"
    fi
    if proxy_env="$(launchctl asuser "$(gost_env_uid)" launchctl getenv HTTP_PROXY 2>/dev/null)"; then
        echo "Eski GUI oturum HTTP_PROXY: $proxy_env"
    fi
    if [[ -d "$RESOLVER_DIR" ]] && ls "$RESOLVER_DIR"/* >/dev/null 2>&1; then
        echo "Per-domain DNS (/etc/resolver): $(ls "$RESOLVER_DIR" | tr '\n' ' ')"
    fi
    ;;
*)
    echo "kullanim: sudo $0 {on|off|status}" >&2
    exit 1
    ;;
esac
